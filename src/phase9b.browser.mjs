import test, { before, after } from 'node:test'
import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { switchBrowserServer } from './switchBrowserServer.mjs'

let app, browser
const source = await readFile('backend/tests/fixtures/phase9b/fortios.conf', 'utf8')
const panosSource = (await readFile('backend/tests/fixtures/phase9b/panos.xml', 'utf8')).replace(/\r\n/g, '\n')
before(async () => {
  app = await switchBrowserServer()
  const { chromium } = await import(process.env.CONFIGHOP_PLAYWRIGHT_MODULE || 'playwright')
  browser = await chromium.launch({ headless: true, executablePath: process.env.CONFIGHOP_CHROMIUM_EXECUTABLE })
  await mkdir('artifacts/phase9b', { recursive: true })
})
after(async () => { await browser?.close(); await app?.close() })

test('real FortiOS to PAN-OS browser path gates export and rejects stale preview', { timeout: 60000 }, async t => {
  const page = await browser.newPage({ viewport: { width: 1680, height: 980 }, acceptDownloads: true })
  t.after(() => page.close())
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  t.after(() => assert.deepEqual(errors, []))
  await page.goto(app.url)
  await page.getByRole('button', { name: 'Cross-vendor Firewall' }).click()
  await page.locator('.phase9b-workspace input[type=file]').setInputFiles({ name: 'phase9b-synthetic.conf', mimeType: 'text/plain', buffer: Buffer.from(source) })
  await page.getByLabel('Target interfaces for port1').fill('ethernet1/1')
  await page.getByLabel('Target interfaces for port2').fill('ethernet1/2')
  await page.locator('.live-heading').getByText('REVIEW_REQUIRED', { exact: true }).waitFor()
  assert.ok(await page.getByRole('button', { name: 'Export Migration Candidate' }).isDisabled())
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('button', { name: 'Copy All', exact: true }).click()
  const text = await page.evaluate(() => navigator.clipboard.readText())
  assert.match(text, /<config version="11\.1\.0">/)
  assert.match(text, /<destination-translation>/)
  await page.getByRole('button', { name: 'Expand configuration preview' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Restore' }).click()
  await page.screenshot({ path: 'artifacts/phase9b/fortios-to-panos-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'artifacts/phase9b/fortios-to-panos-narrow.png', fullPage: true })
  await page.getByLabel('I acknowledge the current review findings.').check()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export Migration Candidate' }).click()
  const file = await download
  assert.equal((await readFile(await file.path(), 'utf8')).replace(/\r\n/g, '\n'), text.replace(/\r\n/g, '\n'))
  await page.getByLabel('Target interfaces for port2').fill('ethernet1/1')
  assert.ok(await page.getByRole('button', { name: 'Export Migration Candidate' }).isDisabled())
  await page.locator('.live-heading').getByText('BLOCKED', { exact: true }).waitFor()
  await page.getByRole('tab', { name: /Validation/ }).click()
  assert.ok(await page.getByText(/NAME_COLLISION/).count() > 0)
})

test('real PAN-OS to FortiOS path renders CLI and blocks App-ID broadening', { timeout: 60000 }, async t => {
  const page = await browser.newPage({ viewport: { width: 1680, height: 980 } })
  t.after(() => page.close())
  await page.goto(app.url)
  await page.getByRole('button', { name: 'Cross-vendor Firewall' }).click()
  await page.getByLabel('Source firewall OS').selectOption('panos')
  const upload = text => page.locator('.phase9b-workspace input[type=file]').setInputFiles({ name: 'phase9b-synthetic.xml', mimeType: 'application/xml', buffer: Buffer.from(text) })
  await upload(panosSource)
  await page.getByLabel('Target interfaces for ethernet1/1').fill('port1')
  await page.getByLabel('Target interfaces for ethernet1/2').fill('port2')
  await page.locator('.live-heading').getByText('REVIEW_REQUIRED', { exact: true }).waitFor()
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('button', { name: 'Copy All', exact: true }).click()
  const text = await page.evaluate(() => navigator.clipboard.readText())
  assert.match(text, /config firewall policy/)
  assert.match(text, /set poolname "pool-snat-1"/)
  assert.ok(await page.locator('.syntax-tag').count() > 0)
  await page.screenshot({ path: 'artifacts/phase9b/panos-to-fortios-desktop.png', fullPage: true })
  const restrictedSource = panosSource.replace('<member>any</member>\n                  </application>', '<member>ssl</member>\n                  </application>')
  assert.notEqual(restrictedSource, panosSource)
  await upload(restrictedSource)
  await page.getByLabel('Target interfaces for ethernet1/1').fill('port1')
  await page.getByLabel('Target interfaces for ethernet1/2').fill('port2')
  await page.locator('.live-heading').getByText('BLOCKED', { exact: true }).waitFor()
  assert.ok(await page.getByRole('button', { name: 'Export Migration Candidate' }).isDisabled())
})

test('paste and delayed preview cannot restore an obsolete mapping', { timeout: 60000 }, async t => {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  t.after(() => page.close())
  await page.goto(app.url)
  await page.getByRole('button', { name: 'Cross-vendor Firewall' }).click()
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.evaluate(value => navigator.clipboard.writeText(value), source)
  await page.getByRole('button', { name: 'Paste', exact: true }).click()
  await page.getByLabel('Target interfaces for port1').fill('ethernet1/1')
  await page.getByLabel('Target interfaces for port2').fill('ethernet1/2')
  await page.locator('.live-heading').getByText('REVIEW_REQUIRED', { exact: true }).waitFor()
  let release, started
  const gate = new Promise(resolve => { release = resolve })
  const seen = new Promise(resolve => { started = resolve })
  let held = false
  await page.route('**/firewall-projects/*/preview', async route => {
    const response = await route.fetch()
    if (!held) { held = true; started(); await gate }
    await route.fulfill({ response }).catch(() => {})
  })
  await page.getByLabel('Target interfaces for port2').fill('ethernet1/3')
  await seen
  await page.getByLabel('Target interfaces for port2').fill('ethernet1/4')
  await page.locator('.live-heading').getByText('REVIEW_REQUIRED', { exact: true }).waitFor()
  release()
  await page.getByRole('button', { name: 'Copy All', exact: true }).click()
  const text = await page.evaluate(() => navigator.clipboard.readText())
  assert.match(text, /ethernet1\/4/)
  assert.doesNotMatch(text, /ethernet1\/3/)
  await page.getByRole('button', { name: 'Save Project', exact: true }).click()
  const stored = await page.evaluate(() => localStorage.getItem('confighop-firewall-cross-vendor-v1'))
  assert.ok(stored && !stored.includes('config system interface'))
})

test('oversized replacement source invalidates the previous export immediately', { timeout: 60000 }, async t => {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  t.after(() => page.close())
  await page.goto(app.url)
  await page.getByRole('button', { name: 'Cross-vendor Firewall' }).click()
  const picker = page.locator('.phase9b-workspace input[type=file]')
  await picker.setInputFiles({ name: 'source.conf', mimeType: 'text/plain', buffer: Buffer.from(source) })
  await page.getByLabel('Target interfaces for port1').fill('ethernet1/1')
  await page.getByLabel('Target interfaces for port2').fill('ethernet1/2')
  await page.locator('.live-heading').getByText('REVIEW_REQUIRED', { exact: true }).waitFor()
  await page.getByLabel('I acknowledge the current review findings.').check()
  assert.ok(await page.getByRole('button', { name: 'Export Migration Candidate' }).isEnabled())
  await picker.setInputFiles({ name: 'too-large.conf', mimeType: 'text/plain', buffer: Buffer.alloc(2 * 1024 * 1024 + 1) })
  await page.getByRole('alert').getByText('Source exceeds the 2 MB limit.').waitFor()
  assert.ok(await page.getByRole('button', { name: 'Export Migration Candidate' }).isDisabled())
  assert.equal(await page.locator('.phase9b-workspace').getByText('No configuration loaded').count(), 1)
})
